using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Runtime.Serialization;
using System.Runtime.Serialization.Json;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

public sealed class GeneratePluginDeclaration : Task
{
    [Required]
    public string Id { get; set; }
    public string DisplayName { get; set; }
    public string PluginVersion { get; set; }

    [Required]
    public string RootNamespace { get; set; }
    public ITaskItem[] Entries { get; set; }
    public ITaskItem[] Projects { get; set; }
    public ITaskItem[] Identities { get; set; }
    public ITaskItem[] Packages { get; set; }
    public ITaskItem[] PackageIdentities { get; set; }
    public ITaskItem[] References { get; set; }

    [Required]
    public string OutputDirectory { get; set; }

    [DataContract]
    private sealed class Declaration
    {
        [DataMember(Name = "id")]
        public string Id;

        [DataMember(Name = "name")]
        public string Name;

        [DataMember(Name = "version", EmitDefaultValue = false)]
        public string Version;

        [DataMember(Name = "entryPoints")]
        public Dictionary<string, string> Entries = new Dictionary<string, string>();

        [DataMember(Name = "requires")]
        public List<Dictionary<string, string>> Requires = new List<Dictionary<string, string>>();

        [DataMember(Name = "compatibleWith")]
        public List<Dictionary<string, string>> CompatibleWith = new List<Dictionary<string, string>>();
    }

    public override bool Execute()
    {
        var manifest = new Declaration
        {
            Id = Id,
            Name = string.IsNullOrEmpty(DisplayName) ? Id : DisplayName,
            Version = PluginVersion,
        };
        var members = new StringBuilder();
        if (Entries?.Length > 0)
            members.AppendLine("    private static T Create<T>() where T : new() => new T();");
        AddIdentity(members, "Id", Id);
        foreach (var entry in Entries ?? Array.Empty<ITaskItem>())
        {
            var kind = entry.ItemSpec;
            var type = entry.GetMetadata("Type");
            if (
                !(kind == "Server" || kind == "Client" || kind == "ClientGui" || kind == "ClientCli")
                || manifest.Entries.ContainsKey(kind)
            )
            {
                Log.LogError("Unknown or duplicate PluginEntryPoint '{0}'.", kind);
                continue;
            }
            manifest.Entries.Add(kind, type);
            var contract = kind == "Server" ? "IApplicationPlugin" : "IPluginFrontend";
            members.AppendLine(
                $"    internal static global::LazyTuiHub.Sdk.{contract} {kind}() => Create<global::{type.Replace('+', '.')}>();"
            );
        }

        var ids = (Identities ?? Array.Empty<ITaskItem>()).ToDictionary(
            item => item.ItemSpec,
            item => item.GetMetadata("PluginId")
        );
        foreach (var project in Projects ?? Array.Empty<ITaskItem>())
            AddReference(manifest, members, project, ids[project.GetMetadata("FullPath")]);
        var packages = (PackageIdentities ?? Array.Empty<ITaskItem>()).ToDictionary(
            item => item.ItemSpec,
            item => item.GetMetadata("PluginId"),
            StringComparer.OrdinalIgnoreCase
        );
        foreach (var package in Packages ?? Array.Empty<ITaskItem>())
        {
            if (packages.TryGetValue(package.ItemSpec, out var id))
                AddReference(manifest, members, package, id);
            else
                Log.LogError("Package '{0}' did not supply its LazyTuiHub plugin identity.", package.ItemSpec);
        }
        foreach (var reference in References ?? Array.Empty<ITaskItem>())
            AddReference(manifest, members, reference, reference.ItemSpec);
        if (Log.HasLoggedErrors)
            return false;

        var json = new DataContractJsonSerializer(
            typeof(Declaration),
            new DataContractJsonSerializerSettings { UseSimpleDictionaryFormat = true }
        );
        Directory.CreateDirectory(OutputDirectory);
        using (var buffer = new MemoryStream())
        {
            json.WriteObject(buffer, manifest);
            WriteChanged("plugin.json", Encoding.UTF8.GetString(buffer.ToArray()));
        }
        WriteChanged(
            "PluginProject.g.cs",
            $"// <auto-generated/>\nglobal using PluginProject = global::{RootNamespace}.Generated.PluginProject;\nnamespace {RootNamespace}.Generated;\ninternal static class PluginProject\n{{\n{members}}}\n"
        );
        return true;
    }

    private void AddIdentity(StringBuilder members, string name, string id)
    {
        if (!Regex.IsMatch(id, @"\Alazytuihub\.plugin\.(?:[a-z0-9]+(?:-[a-z0-9]+)*\.)+[a-z0-9]+(?:-[a-z0-9]+)*\z"))
            Log.LogError("Invalid plugin ID '{0}'.", id);
        else
            members.AppendLine($"    internal const string {name} = \"{id}\";");
    }

    private void AddReference(Declaration manifest, StringBuilder members, ITaskItem reference, string id)
    {
        var alias = reference.GetMetadata("PluginAlias");
        if (alias.Length > 0)
            AddIdentity(members, alias, id);
        var relation = reference.GetMetadata("PluginRelation");
        if (relation.Length == 0)
            return;
        var dependency = new Dictionary<string, string> { ["id"] = id };
        var range = reference.GetMetadata("PluginVersionRange");
        if (range.Length > 0)
            dependency.Add("version", range);
        switch (relation)
        {
            case "Requires":
                manifest.Requires.Add(dependency);
                break;
            case "CompatibleWith":
                manifest.CompatibleWith.Add(dependency);
                break;
            default:
                Log.LogError("Unknown PluginRelation '{0}' on '{1}'.", relation, reference.ItemSpec);
                break;
        }
    }

    private void WriteChanged(string filename, string value)
    {
        var path = Path.Combine(OutputDirectory, filename);
        if (!File.Exists(path) || File.ReadAllText(path) != value)
            File.WriteAllText(path, value, new UTF8Encoding(false));
    }
}
